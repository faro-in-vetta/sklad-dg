-- Виконувати ПІСЛЯ 15_adj_to_receipt.sql. Файл можна виконувати повторно.
--
-- Застосунок раніше рахував наступний код по тому, що вже завантажив у
-- пам'ять. Дані оновлюються раз на 45 секунд, тож двоє, які відкрили
-- «Новий SKU» одночасно, бачили один і той самий код. Перший зберігав,
-- другий упирався в «штрихкод зайнято» і не міг зберегти картку взагалі.
--
-- Ця функція повертає наступний вільний код прямо з бази — вона бачить і
-- щойно створені картки, і видалені (їхні коди не переприсвоюються).
-- Застосунок питає її, коли відкриває форму, і ще раз, якщо при збереженні
-- код усе-таки зайняли: тоді картка тихо отримує наступний вільний, а
-- людина бачить повідомлення, який код друкувати на етикетці.
-- =====================================================================

create or replace function next_sku_code() returns text
language plpgsql security definer set search_path = public stable as $$
declare n bigint;
begin
  if not is_member() then
    raise exception 'Немає доступу';
  end if;
  select coalesce(max(nullif(regexp_replace(code,'\D','','g'),'')::bigint), 0)
    into n from skus where code ~ '^DG[0-9]+$';
  return 'DG' || lpad((n + 1)::text, 7, '0');
end $$;

revoke all on function next_sku_code() from public, anon;
grant execute on function next_sku_code() to authenticated;


-- перевірка: функція є і повертає наступний код
select next_sku_code() as наступний_вільний;
