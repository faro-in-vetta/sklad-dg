-- ---------------------------------------------------------------------
-- КРОК 1. Що буде переведено: лише ДОДАТНІ коригування (товару побільшало)
-- ---------------------------------------------------------------------
select o.id,
       o.happened_on                     as дата,
       s.maker || ' · ' || s.art || ' · ' || coalesce(s.color,'') as sku,
       o.kg                              as кг,
       o.cones                           as конусів,
       o.comment                         as коментар
  from ops o
  join skus s on s.id = o.sku_id
 where o.type = 'adj'
   and (o.kg > 0 or o.cones > 0)
   and o.kg >= 0 and o.cones >= 0
 order by o.happened_on, s.art;


